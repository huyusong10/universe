def write_atlas(nodes,triangles,records,report,core_end,out,metadata_output):
 """Index exact position/normal pairs, retaining separate source derivatives."""
 assert np.isfinite(nodes).all() and np.isfinite(triangles).all()
 for record in records.values():
  def balanced(slot,end):
   escape=int(nodes[slot,0,3]);payload=int(nodes[slot,1,3]);assert escape==end
   if payload>=0:
    assert end==slot+1
    return
   right=-payload-1;assert right-slot-1==end-right
   balanced(slot+1,right);balanced(right,end)
  balanced(record['root'],record['end'])
 total=len(triangles);vertex_offset=0;files=[]
 for part,start,end in [('worlds',(0,0),core_end),('rosetta',core_end,(len(nodes),total))]:
  if start==end:continue
  faces=triangles[start[1]:end[1]].view('<u4')
  pairs=np.concatenate([faces[:,:3],faces[:,3:]],axis=2).reshape((-1,8))
  vertices,inverse=np.unique(pairs,axis=0,return_inverse=True)
  headers=np.zeros((len(faces),4),'<u4');headers[:,:3]=(total+2*(inverse.reshape((-1,3))+vertex_offset)).astype('<u4')
  # Every float32 bit, including normal seams and signed zero, is retained.
  restored=vertices[inverse].reshape((-1,3,8))
  assert np.array_equal(restored[:,:,:4],faces[:,:3]) and np.array_equal(restored[:,:,4:],faces[:,3:])
  data=np.concatenate([headers.ravel(),vertices.astype('<u4').ravel()])
  for kind,raw in [('nodes',nodes[start[0]:end[0]].tobytes()),('triangles',data.tobytes())]:
   filename=f'{part}-{kind}.bin';(out/filename).write_bytes(raw)
   item={'part':part,'kind':kind,'file':filename,'bytes':len(raw),'sha256':hashlib.sha256(raw).hexdigest()}
   packed=gzip.compress(raw,compresslevel=9,mtime=0);packed_file=filename+'.gz';(out/packed_file).write_bytes(packed)
   item['packed']={'file':packed_file,'bytes':len(packed),'sha256':hashlib.sha256(packed).hexdigest(),'encoding':'gzip'}
   if kind=='triangles':item.update(triangleCount=len(faces),vertexCount=len(vertices))
   files.append(item)
  vertex_offset+=len(vertices)
