def smooth(a,b,x):
 t=np.clip((x-a)/(b-a),0,1);return t*t*(3-2*t)

def relief_noise(points):
 # Offline, seeded-in-space value noise. Smooth random cells replace the
 # crossed periodic waves that become a visible lattice on dense geometry.
 cell=np.floor(points).astype(np.int64);t=points-cell;w=t*t*t*(t*(t*6-15)+10)
 result=np.zeros(len(points))
 for x in range(2):
  for y in range(2):
   for z in range(2):
    c=cell+np.array([x,y,z]);n=((c[:,0]*73856093)^(c[:,1]*19349663)^(c[:,2]*83492791)).astype(np.uint32)
    n=(n^(n>>16))*np.uint32(0x7feb352d);n=(n^(n>>15))*np.uint32(0x846ca68b);n=n^(n>>16)
    weight=(w[:,0] if x else 1-w[:,0])*(w[:,1] if y else 1-w[:,1])*(w[:,2] if z else 1-w[:,2])
    result+=(n.astype(np.float64)/4294967296)*weight
 return result*2-1

def dogbone_loft():
 # A longitudinal cross-section can represent the narrow bridge without
 # stretching angular faces across disconnected radial intersections.
 # Unequal lobes and their connecting shape remain an authored illustration.
 sections=129;sides=192;vertices=[[-.99,0,0]];faces=[]
 def softmax(a,b,k):return max(a,b)+max(0,k-abs(a-b))**2/(4*k)
 for x in np.linspace(-.99,1.01,sections)[1:-1]:
  left=math.sqrt(max(0,1-((x+.56)/.43)**2));right=math.sqrt(max(0,1-((x-.52)/.49)**2))
  bridge=.29*float(smooth(-.66,-.48,x))*(1-float(smooth(.54,.70,x)))
  ry=softmax(softmax(.73*left,.77*right,.045),bridge,.035)
  rz=softmax(softmax(.76*left,.79*right,.045),bridge,.035)
  cy=.035*float(smooth(-.14,.46,x))
  for j in range(sides):
   angle=math.tau*j/sides;vertices.append([x,cy+ry*math.cos(angle),rz*math.sin(angle)])
 for j in range(sides):faces.append([0,1+(j+1)%sides,1+j])
 for row in range(sections-3):
  for j in range(sides):
   a=1+row*sides+j;d=1+row*sides+(j+1)%sides;b=a+sides;c=d+sides
   faces.extend([[a,d,b],[b,d,c]])
 cap=len(vertices);vertices.append([1.01,.035,0]);last=1+(sections-3)*sides
 for j in range(sides):faces.append([cap,last+j,last+(j+1)%sides])
 return np.array(vertices),np.array(faces,np.int32)

