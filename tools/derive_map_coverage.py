#!/usr/bin/env python3
"""Derive advisory camera coverage from the existing partial-map alpha channels.

Requires Pillow. This does not alter imagery or claim measured source footprints.
Run from any directory after replacing a partial map.
"""
import hashlib
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
WIDTH, HEIGHT = 32, 16
profiles = {}
for path in sorted((ROOT / 'assets/planets').glob('*.png')):
    with Image.open(path) as image:
        alpha = image.convert('RGBA').getchannel('A')
        if alpha.getextrema() == (255, 255):
            continue
        profiles[path.stem] = {
            'source': str(path.relative_to(ROOT)),
            'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
            'alpha': alpha.resize((WIDTH, HEIGHT), Image.Resampling.BOX).tobytes().hex(),
        }
output = ('// Generated by tools/derive_map_coverage.py; advisory source-alpha coverage.\n'
          '// Not a measured footprint, relief map or replacement for source pixels.\n'
          'export const MAP_MERIDIANS = Object.freeze({ pluto: -2.25, charon: -2.25, ceres: -.35 });\n'
          f'export const MAP_COVERAGE_SIZE = Object.freeze([{WIDTH}, {HEIGHT}]);\n'
          'export const MAP_COVERAGE = Object.freeze(' + json.dumps(profiles, indent=2) + ');\n')
(ROOT / 'assets/observatory-map-coverage-data.js').write_text(output)
